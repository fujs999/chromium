namespace media {
class VaapiWrapper;

// This class provides an H.265 (HEVC) Main profile encoder functionality,
// generating stream headers, managing encoder state, reference frames, and
// other codec parameters, while requiring support from a VA-API driver to
// encode frame data based on these parameters.
//
// The produced stream is a low delay stream of a single layer: an IDR picture
// followed by pictures that each reference the previous picture only. The rate
// control is delegated to the driver (constant bitrate).
//
// This class must be created, called and destroyed on a single sequence.
//
// Names used in documentation of this class refer directly to naming used
// in the H.265 specification (http://www.itu.int/rec/T-REC-H.265).
class H265VaapiVideoEncoderDelegate : public VaapiVideoEncoderDelegate {
 public:
  struct EncodeParams {
    EncodeParams();

    VideoBitrateAllocation bitrate_allocation;

    // Framerate in FPS.
    uint32_t framerate;

    // Bitrate window size in ms.
    uint32_t cpb_window_size_ms;

    // Bitrate window size in bits.
    uint32_t cpb_size_bits;

    // Quantization parameters. Their ranges are 0-51.
    uint8_t initial_qp;
    uint8_t min_qp;
    uint8_t max_qp;
  };

  H265VaapiVideoEncoderDelegate(scoped_refptr<VaapiWrapper> vaapi_wrapper,
                                base::RepeatingClosure error_cb);

  H265VaapiVideoEncoderDelegate(const H265VaapiVideoEncoderDelegate&) = delete;
  H265VaapiVideoEncoderDelegate& operator=(
      const H265VaapiVideoEncoderDelegate&) = delete;

  ~H265VaapiVideoEncoderDelegate() override;

  // VaapiVideoEncoderDelegate implementation.
  bool Initialize(const VideoEncodeAccelerator::Config& config,
                  const VaapiVideoEncoderDelegate::Config& ave_config) override;
  bool UpdateRates(const VideoBitrateAllocation& bitrate_allocation,
                   uint32_t framerate) override;
  gfx::Size GetCodedSize() const override;
  size_t GetMaxNumOfRefFrames() const override;
  std::vector<gfx::Size> GetSVCLayerResolutions() override;

 private:
  friend class H265VaapiVideoEncoderDelegateTest;

  // VaapiVideoEncoderDelegate implementation.
  PrepareEncodeJobResult PrepareEncodeJob(EncodeJob& encode_job) override;
  BitstreamBufferMetadata GetMetadata(const EncodeJob& encode_job,
                                      size_t payload_size) override;
  void BitrateControlUpdate(const BitstreamBufferMetadata& metadata) override;

  // Sets |level_idc_| in |vps_| and |sps_|, and regenerates
  // |packed_parameter_sets_| from |vps_|, |sps_| and |pps_|.
  void UpdateParameterSets();

  // Generates the slice segment header NALU of |pic| into
  // |packed_slice_header|. The syntax elements are taken from |sps_|, |pps_|,
  // |pic_param| and |slice_param| so that the header is consistent with the
  // parameters submitted to the driver.
  void GeneratePackedSliceHeader(
      H26xAnnexBBitstreamBuilder& packed_slice_header,
      const VAEncPictureParameterBufferHEVC& pic_param,
      const VAEncSliceParameterBufferHEVC& slice_param,
      const H265Picture& pic) const;

  // Submits the parameter buffers and the packed headers of |pic| to the
  // driver. |ref_pic| is the picture referenced by |pic|, or null if |pic| is
  // an IDR picture.
  bool SubmitFrameParameters(EncodeJob& job,
                             H265Picture& pic,
                             H265Picture* ref_pic);

  // Current parameter sets. They only change if the level has to be raised.
  H265VPS vps_;
  H265SPS sps_;
  H265PPS pps_;

  // The VPS, SPS and PPS NALUs in AnnexB format *with* emulation prevention
  // three-byte sequences. They are submitted with every IDR picture if
  // |submit_packed_parameter_sets_| is true.
  H26xAnnexBBitstreamBuilder packed_parameter_sets_{
      /*insert_emulation_prevention_bytes=*/true};

  // Whether the driver accepts the parameter sets and the slice segment header
  // generated by this class. If it doesn't, they are generated by the driver.
  bool submit_packed_parameter_sets_ = false;
  bool submit_packed_slice_header_ = false;

  // True if the driver doesn't support P slices. The inter pictures are then
  // encoded as generalized P and B (GPB) pictures, i.e. with B slices whose
  // two reference picture lists are identical.
  bool use_gpb_ = false;

  // Current encoding parameters being used.
  EncodeParams curr_params_;

  // general_level_idc currently used, i.e. 30 times the level number.
  uint8_t level_idc_ = 0;

  // Current visible and coded sizes in pixels.
  gfx::Size visible_size_;
  gfx::Size coded_size_;

  // The number of coding tree units in a picture.
  uint32_t num_ctus_in_pic_ = 0;

  // The number of encoded frames. Resets to 0 on IDR frame. It is also the
  // picture order count of the next frame.
  uint32_t num_encoded_frames_ = 0;

  // True if encoding parameters have changed that affect decoder process, then
  // we need to submit a keyframe with updated parameters.
  bool encoding_parameters_changed_ = false;

  // The picture referenced by the next inter picture, i.e. the previously
  // encoded picture.
  scoped_refptr<H265Picture> ref_pic_;
};

}  // namespace media

#endif  // MEDIA_GPU_VAAPI_H265_VAAPI_VIDEO_ENCODER_DELEGATE_H_
